export type FootId =
  | 'faulun'
  | 'mafailun'
  | 'mustafilun'
  | 'failun'
  | 'failatun'
  | 'mutafailun'
  | 'mufaalatun'
  | 'mafulatu';

export interface FootVariant {
  /** التمثيل الرمزي بعد التغيير. */
  pattern: string;
  /** اسم التفعيلة الناتجة، مشكولة. */
  name: string;
  /** اسم الزحاف أو العلّة. */
  change: string;
  /** كلفة الاختيار عند الترجيح: 0 سالم، 1 زحاف، 2 زحاف مركّب. */
  cost: number;
}

export interface Foot {
  id: FootId;
  /** التفعيلة سالمة، مشكولة. */
  name: string;
  /** بلا تشكيل — للعناوين والروابط. */
  plain: string;
  slug: string;
  pattern: string;
  /** تركيب التفعيلة من أسباب وأوتاد. */
  build: string[];
  syllables: string[];
  pronunciation: string;
  description: string;
  /** الزحافات الجائزة في الحشو. */
  zihafat: FootVariant[];
  /** العلل الجارية في العروض والضرب. */
  ilal: FootVariant[];
  meters: string[];
}

const v = (pattern: string, name: string, change: string, cost = 1): FootVariant => ({
  pattern,
  name,
  change,
  cost,
});

