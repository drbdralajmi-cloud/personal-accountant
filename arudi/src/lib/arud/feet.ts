/** عدد المقاطع العروضية (كل سبب أو وتد مقطع). */
export function countSyllables(pattern: string): number {
  return splitSyllables(pattern).length;
}

/**
 * تقسيم التمثيل الرمزي إلى مقاطع عروضية:
 * المقطع القصير 1، والمقطع الطويل 10، والمقطع المديد 100.
 */
export function splitSyllables(pattern: string): string[] {
  const out: string[] = [];
  let i = 0;
  while (i < pattern.length) {
    if (pattern[i] === '1' && pattern[i + 1] === '0') {
      if (pattern[i + 2] === '0') {
        out.push('100');
        i += 3;
      } else {
        out.push('10');
        i += 2;
      }
    } else {
      out.push(pattern[i]);
      i += 1;
    }
  }
  return out;
}

