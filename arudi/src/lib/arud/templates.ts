export const TEMPLATES: Template[] = [...ROOT_TEMPLATES, ...DERIVED_TEMPLATES];

export const ROOT_TEMPLATE_LIST = ROOT_TEMPLATES;
export const DERIVED_TEMPLATE_LIST = DERIVED_TEMPLATES;

export const templateBySlug = (slug: string): Template | undefined =>
  TEMPLATES.find((t) => t.slug === slug);

/** كل القوالب التي تحمل هذا الاسم بلا تشكيل — «فعلن» تعطي صورتين. */
export const templatesByPlain = (plain: string): Template[] =>
  TEMPLATES.filter((t) => t.plain === plain || t.aliases.some((a) => stripHarakat(a) === plain));

const HARAKAT = /[ً-ْٰـ]/g;
export const stripHarakat = (s: string) => s.replace(HARAKAT, '');

/** فحص داخليّ: كل قالب يجب أن يتّسق اسمه المشكول مع رمزه وعدد مقاطعه. */
export function templateIssues(): string[] {
  const out: string[] = [];
  for (const t of TEMPLATES) {
    if (splitSyllables(t.pattern).length !== t.syllables.length) {
      out.push(`${t.name}: عدد المقاطع المكتوبة (${t.syllables.length}) يخالف الرمز.`);
    }
    if (stripHarakat(t.name) !== t.plain) {
      out.push(`${t.name}: الاسم بلا تشكيل لا يطابق الحقل plain.`);
    }
    if (!/^[01]+$/.test(t.pattern)) out.push(`${t.name}: رمز غير صالح.`);
    if (t.kind === 'فرع' && !t.origins.length) out.push(`${t.name}: صورة فرعية بلا أصل.`);
  }
  return out;
}
