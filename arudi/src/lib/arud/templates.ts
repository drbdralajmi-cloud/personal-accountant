/**
 * القوالب الشعرية = التفعيلات الثماني الأصول + صورها المتفرّعة.
 *
 * الخليل ركّب من الأسباب والأوتاد ثماني تفعيلات لا تاسع لها، لكنّ الشعر
 * لا يجري عليها سالمةً وحدها؛ فالزحافات والعلل تولّد منها صوراً أخرى لها
 * أسماء مستقلّة يتداولها الناس ويطلبون الكلمات على وزنها — أشهرها (فَعِلُنْ)
 * و(فَعْلُنْ) و(مَفَاعِلُنْ) و(مُفْتَعِلُنْ). هذا الملفّ يجعل تلك الصور
 * قوالبَ من الدرجة الأولى: لها صفحات وشروح وكلمات على أوزانها، مع بيان
 * أصلها والتغيير الذي وَلَدها.
 *
 * ملاحظة مهمّة: الصورة الواحدة قد تتفرّع عن أكثر من أصل — (مَفَاعِلُنْ)
 * تكون خبنَ (مُسْتَفْعِلُنْ) وقبضَ (مَفَاعِيلُنْ) وعقلَ (مُفَاعَلَتُنْ)،
 * ورمزها واحد. ولذلك يُذكر لكل قالب فرعيّ كلُّ أصوله لا أصلٌ واحد.
 */

import { FEET_LIST, FootId, splitSyllables } from './feet';

export interface TemplateOrigin {
  foot: FootId;
  /** اسم التغيير الذي ولّد هذه الصورة من ذلك الأصل. */
  change: string;
}

export interface Template {
  slug: string;
  /** الاسم مشكولاً. */
  name: string;
  /** بلا تشكيل — للبحث والروابط. */
  plain: string;
  pattern: string;
  kind: 'أصل' | 'فرع';
  /** أسماء أخرى للصورة نفسها (مترادفات العروضيين). */
  aliases: string[];
  origins: TemplateOrigin[];
  build: string[];
  syllables: string[];
  pronunciation: string;
  description: string;
  meters: string[];
  /** تنبيه يُعرض في صدر الصفحة عند الاقتضاء (الالتباس في الأسماء مثلاً). */
  caution?: string;
}

